-- ECC Supabase Database Setup Script
-- Run this in the Supabase SQL Editor after creating the project.
-- Then create an Auth user for each admin and insert that user's UUID into public.site_admins.

BEGIN;

-- 1. Tables

CREATE TABLE IF NOT EXISTS public.site_admins (
    user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
    role TEXT NOT NULL CHECK (char_length(role) BETWEEN 1 AND 80),
    bio TEXT CHECK (char_length(coalesce(bio, '')) <= 500),
    skills TEXT CHECK (char_length(coalesce(skills, '')) <= 250),
    year TEXT CHECK (char_length(coalesce(year, '')) <= 40),
    github TEXT DEFAULT '#' CHECK (github IS NULL OR github = '#' OR github ~* '^https?://'),
    linkedin TEXT DEFAULT '#' CHECK (linkedin IS NULL OR linkedin = '#' OR linkedin ~* '^https?://'),
    photo_url TEXT CHECK (photo_url IS NULL OR photo_url = '' OR photo_url ~* '^https?://'),
    initials TEXT CHECK (char_length(coalesce(initials, '')) <= 4),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
    "desc" TEXT CHECK (char_length(coalesce("desc", '')) <= 600),
    category TEXT NOT NULL DEFAULT 'other' CHECK (category IN ('web', 'mobile', 'ai', 'cloud', 'security', 'other')),
    status TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Completed', 'Archived')),
    tech TEXT CHECK (char_length(coalesce(tech, '')) <= 250),
    icon TEXT DEFAULT 'CODE' CHECK (char_length(coalesce(icon, '')) <= 16),
    github_url TEXT DEFAULT '#' CHECK (github_url IS NULL OR github_url = '#' OR github_url ~* '^https?://'),
    demo_url TEXT DEFAULT '#' CHECK (demo_url IS NULL OR demo_url = '#' OR demo_url ~* '^https?://'),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
    "desc" TEXT CHECK (char_length(coalesce("desc", '')) <= 600),
    date DATE NOT NULL,
    type TEXT NOT NULL DEFAULT 'Other' CHECK (type IN ('Hackathon', 'Competition', 'Workshop', 'Conference', 'Sprint', 'Talk', 'Other')),
    status TEXT NOT NULL DEFAULT 'upcoming' CHECK (status IN ('upcoming', 'ongoing', 'past')),
    venue TEXT CHECK (char_length(coalesce(venue, '')) <= 120),
    participants INTEGER DEFAULT 0 CHECK (participants BETWEEN 0 AND 100000),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    members_count INTEGER DEFAULT 0 CHECK (members_count BETWEEN 0 AND 100000),
    projects_count INTEGER DEFAULT 0 CHECK (projects_count BETWEEN 0 AND 100000),
    hackathons_count INTEGER DEFAULT 0 CHECK (hackathons_count BETWEEN 0 AND 100000),
    awards_count INTEGER DEFAULT 0 CHECK (awards_count BETWEEN 0 AND 100000),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 80),
    email TEXT NOT NULL CHECK (char_length(email) <= 150 AND email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
    topic TEXT NOT NULL CHECK (topic IN ('Join ECC', 'Collaboration', 'Sponsorship', 'General Query')),
    message TEXT NOT NULL CHECK (char_length(message) BETWEEN 1 AND 1000),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Grants for the Data API


-- 4. Storage
-- Current Supabase Storage supports per-bucket file_size_limit and allowed_mime_types.

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
    'member-photos',
    'member-photos',
    true,
    2097152,
    ARRAY['image/jpeg', 'image/png', 'image/webp']
)
ON CONFLICT (id) DO UPDATE
SET public = EXCLUDED.public,
    file_size_limit = EXCLUDED.file_size_limit,
    allowed_mime_types = EXCLUDED.allowed_mime_types;

DROP POLICY IF EXISTS "Public can view member photos" ON storage.objects;
DROP POLICY IF EXISTS "Site admins can upload member photos" ON storage.objects;
DROP POLICY IF EXISTS "Site admins can update member photos" ON storage.objects;
DROP POLICY IF EXISTS "Site admins can delete member photos" ON storage.objects;

CREATE POLICY "Public can view member photos"
ON storage.objects
FOR SELECT
TO anon, authenticated
USING (bucket_id = 'member-photos');

CREATE POLICY "Site admins can upload member photos"
ON storage.objects
FOR INSERT
TO authenticated
WITH CHECK (
    bucket_id = 'member-photos'
    AND storage.extension(name) IN ('jpg', 'jpeg', 'png', 'webp')
    AND EXISTS (SELECT 1 FROM public.site_admins WHERE user_id = auth.uid())
);

CREATE POLICY "Site admins can update member photos"
ON storage.objects
FOR UPDATE
TO authenticated
USING (
    bucket_id = 'member-photos'
    AND EXISTS (SELECT 1 FROM public.site_admins WHERE user_id = auth.uid())
)
WITH CHECK (
    bucket_id = 'member-photos'
    AND storage.extension(name) IN ('jpg', 'jpeg', 'png', 'webp')
    AND EXISTS (SELECT 1 FROM public.site_admins WHERE user_id = auth.uid())
);

CREATE POLICY "Site admins can delete member photos"
ON storage.objects
FOR DELETE
TO authenticated
USING (
    bucket_id = 'member-photos'
    AND EXISTS (SELECT 1 FROM public.site_admins WHERE user_id = auth.uid())
);

